-- Dedicated, unexposed schema. Only the trusted server connects to these tables.
CREATE SCHEMA IF NOT EXISTS labtrack;
REVOKE ALL ON SCHEMA labtrack FROM PUBLIC;

CREATE TABLE labtrack.students (
 student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_no varchar(20) NOT NULL UNIQUE,
 full_name varchar(100) NOT NULL,
 course varchar(50) NOT NULL,
 email varchar(100) NOT NULL UNIQUE
);
CREATE TABLE labtrack.categories (
 category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_name varchar(60) NOT NULL UNIQUE,
 description varchar(255)
);
CREATE TABLE labtrack.equipment (
 equipment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 equipment_code varchar(20) NOT NULL UNIQUE,
 equipment_name varchar(100) NOT NULL,
 category_id integer NOT NULL REFERENCES labtrack.categories ON DELETE RESTRICT,
 total_quantity integer NOT NULL CHECK (total_quantity > 0),
 available_quantity integer NOT NULL CHECK (available_quantity >= 0 AND available_quantity <= total_quantity),
 condition_status varchar(20) NOT NULL CHECK (condition_status IN ('Good','For Repair'))
);
CREATE TABLE labtrack.borrowings (
 borrowing_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id integer NOT NULL REFERENCES labtrack.students ON DELETE RESTRICT,
 equipment_id integer NOT NULL REFERENCES labtrack.equipment ON DELETE RESTRICT,
 quantity integer NOT NULL CHECK (quantity > 0),
 borrow_date date NOT NULL,
 due_date date NOT NULL CHECK (due_date >= borrow_date),
 return_date date CHECK (return_date IS NULL OR return_date >= borrow_date),
 status varchar(20) NOT NULL CHECK (status IN ('Borrowed','Returned','Overdue')),
 CHECK ((status = 'Returned' AND return_date IS NOT NULL) OR (status IN ('Borrowed','Overdue') AND return_date IS NULL))
);
CREATE INDEX equipment_category_idx ON labtrack.equipment(category_id);
CREATE INDEX borrowings_student_idx ON labtrack.borrowings(student_id);
CREATE INDEX borrowings_equipment_idx ON labtrack.borrowings(equipment_id);
CREATE INDEX borrowings_due_return_idx ON labtrack.borrowings(return_date,due_date);
CREATE INDEX borrowings_date_idx ON labtrack.borrowings(borrow_date);

ALTER TABLE labtrack.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE labtrack.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE labtrack.equipment ENABLE ROW LEVEL SECURITY;
ALTER TABLE labtrack.borrowings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA labtrack FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA labtrack FROM PUBLIC;
